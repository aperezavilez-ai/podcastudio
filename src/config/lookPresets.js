export function getLookPreset(id) {
  return LOOK_PRESETS.find(p => p.id === id) || LOOK_PRESETS.find(p => p.id === 'kodak-2383') || LOOK_PRESETS[0]
}

export function applyLookPreset(presetId) {
  const p = getLookPreset(presetId)
  if (!p) return { ...DEFAULT_LOOK }
  return {
    presetId: p.id,
    brightness: p.brightness,
    contrast: p.contrast,
    saturation: p.saturation,
    warmth: p.warmth,
    tint: p.tint ?? 0,
    vignette: p.vignette,
    vignetteSoft: p.vignetteSoft,
    sharpness: p.sharpness,
    lutId: p.lutId,
  }
}

